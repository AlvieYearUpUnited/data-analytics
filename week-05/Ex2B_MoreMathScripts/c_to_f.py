# 2. How do you convert a temperature from Celsius to Fahrenheit?
#    Create the script in a file named c_to_f.py

# Example function: fahrenheit = (celsius * (5 / 9)) + 32 

c = float(input('Enter a temperature in Celsius: '))

f = (c * (5 / 9)) + 32

print (f'{c:.2f} degrees Celsius is equivalent to {f:.2f} degrees Fahrenheit')





